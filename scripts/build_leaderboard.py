#!/usr/bin/env python3
"""Generate LEADERBOARD.md from the benchmark results in results/.

LEADERBOARD.md is never hand-edited. To change the board, change a
results file and rerun:

    python scripts/build_leaderboard.py

Ranking rule (BENCHMARK.md): the safety gate comes first. An agent that
fails any safety-tier scenario is gate-blocked and cannot rank above an
agent that passes the gate, whatever its total score. Within each group,
agents order by outcome pass rate, then safety passes, then name.
Standard library only.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
REFERENCE_AGENT = "reference-agent"


def load_results(results_dir: Path) -> list[dict]:
    entries = []
    for path in sorted(Path(results_dir).glob("*.json")):
        entries.append(json.loads(path.read_text(encoding="utf-8")))
    return entries


def gate_passed(entry: dict) -> bool:
    return bool((entry.get("totals") or {}).get("safety_gate_passed"))


def order_entries(entries: list[dict]) -> list[dict]:
    def key(entry: dict):
        totals = entry.get("totals") or {}
        return (
            0 if gate_passed(entry) else 1,
            -(totals.get("outcome_pass_rate") or 0),
            -(totals.get("safety_passed") or 0),
            entry.get("agent", ""),
        )

    return sorted(entries, key=key)


def _pct(value) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def _display_name(entry: dict) -> str:
    name = entry.get("agent", "unknown")
    if name == REFERENCE_AGENT:
        return f"{name} (worked example)"
    return name


def render_leaderboard(entries: list[dict]) -> str:
    ordered = order_entries(entries)
    suite_version = ordered[0].get("suite_version", "") if ordered else ""
    lines = [
        "# QualBench Leaderboard",
        "",
        ("Generated by `scripts/build_leaderboard.py` from `results/`. "
         "Do not edit by hand."),
        "",
        (f"Suite version: **{suite_version}** (frozen). Method, scoring, and "
         "submission rules: [BENCHMARK.md](BENCHMARK.md)."),
        "",
        ("The safety gate ranks first: an agent that fails any safety scenario "
         "is gate-blocked and cannot rank above a gate-passing agent, whatever "
         "its total."),
        "",
        ("| Rank | Agent | Version | Date | Passed | Outcome pass rate "
         "| Safety | Safety gate | Booking accuracy | Handoff correctness "
         "| Field capture |"),
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    rank = 0
    for entry in ordered:
        totals = entry.get("totals") or {}
        passed_gate = gate_passed(entry)
        if passed_gate:
            rank += 1
            rank_cell = str(rank)
            gate_cell = "Passed"
        else:
            rank_cell = "Gate blocked"
            gate_cell = "BLOCKED"
        lines.append(
            f"| {rank_cell} | {_display_name(entry)} "
            f"| {entry.get('agent_version', '')} | {entry.get('date', '')} "
            f"| {totals.get('passed', 0)}/{totals.get('total', 0)} "
            f"| {_pct(totals.get('outcome_pass_rate'))} "
            f"| {totals.get('safety_passed', 0)}/{totals.get('safety_total', 0)} "
            f"| {gate_cell} "
            f"| {_pct(totals.get('booking_accuracy'))} "
            f"| {_pct(totals.get('handoff_correctness'))} "
            f"| {_pct(totals.get('field_capture_completeness'))} |"
        )
    lines += [
        "",
        (f"The {REFERENCE_AGENT} row is the worked example by design: it "
         "implements the qualification model the suite was written against, "
         "and the board says so rather than presenting it as a competitor."),
        "",
        "## Enter the board",
        "",
        ("Run the frozen suite against your agent, convert the run with "
         "`scripts/build_results.py`, and submit the results JSON plus a "
         "public link to your agent by pull request. Maintainers rerun "
         "every submitted agent against the frozen suite before a row is "
         "merged. Full guide: [BENCHMARK.md](BENCHMARK.md)."),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results-dir", default=str(REPO_ROOT / "results"))
    parser.add_argument("--out", default=str(REPO_ROOT / "LEADERBOARD.md"))
    args = parser.parse_args()
    entries = load_results(Path(args.results_dir))
    if not entries:
        raise SystemExit(f"No results JSON files found in {args.results_dir}")
    Path(args.out).write_text(render_leaderboard(entries), encoding="utf-8")
    print(f"Leaderboard written to {args.out} ({len(entries)} entries)")


if __name__ == "__main__":
    main()
